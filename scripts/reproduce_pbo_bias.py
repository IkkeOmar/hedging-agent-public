"""Reproduce the PBO bias table in docs/LITERATURE.md section 11.

Run it:

    python scripts/reproduce_pbo_bias.py            # the table, as text
    python scripts/reproduce_pbo_bias.py --json     # the same, as JSON

The table answers one question: on data with no skill whatsoever, what does
our probability-of-backtest-overfitting estimator read, and what does an
independent implementation read?

Three columns, one protocol:

  before   our estimator, as it was shipped before the fix
  after    our estimator, as it ships now
  ml4t     ``ml4t.diagnostic``, the independent implementation

`before` needs a reference implementation of the old form, because the old
form is not in this repository any more. It is reproduced here, verbatim,
from the commit that fixed it (``e507070``, "Fix PBO bias, crypto
annualisation, and stop hiding tracebacks"). The old form was:

    theta = (rank_of_best - 1.0) / n_cfg_f - 0.5

where the current form is Bailey & Lopez de Prado's

    theta = rank_of_best / (n_cfg_f + 1.0) - 0.5

See notes/KNOWN-TRAPS.md entry 1 for the mechanism and the size of the bias.

THE PROTOCOL, so the numbers are reproducible rather than remembered:

  * one RNG stream, ``numpy.random.default_rng(11)``, draws the matrices;
    ``before`` and ``after`` are computed on the SAME matrix, so the two
    columns differ only in the estimator and never in the data;
  * ``ml4t`` gets its own stream, seeded identically, so it cannot perturb
    the other two columns;
  * 400 draws of a (2000 x N) matrix of iid normals with scale 0.01;
  * 8 splits, which is 70 combinations for our estimator;
  * ``ml4t`` is called with 4 IS/OOS combinations, because its API takes
    precomputed matrices and its resolution is 1/4 -- that quantisation is
    the point of the "Secondary finding" note in the same section.

The truth for every row is 0.5: with no skill, the in-sample winner is no
more likely to end up in the bottom half out-of-sample than not.
"""
from __future__ import annotations

import argparse
import json
import sys
from decimal import ROUND_HALF_UP, Decimal

import numpy as np

from hedging_agent import stats as ha

SEED = 11
N_DRAWS = 400
N_OBS = 2000
N_SPLITS = 8
N_CONFIGS = (6, 10, 12)
ML4T_COMBINATIONS = 4
TRUTH = 0.5


def _half_up(value: float, places: int) -> str:
    """Round half UP, explicitly.

    Python's built-in rounding is half-to-even on the binary double, so
    0.4935 formats as "0.493" while the published table says 0.494. A
    reproduction script that prints a different number from the table it is
    supposed to reproduce is worse than no script, so the rule is stated
    here rather than inherited from float formatting.
    """
    quantum = Decimal(1).scaleb(-places)
    return str(Decimal(repr(value)).quantize(quantum, rounding=ROUND_HALF_UP))


def pbo_pre_fix(matrix: np.ndarray, n_splits: int = N_SPLITS) -> float:
    """Our estimator as it was shipped before the fix (reference copy).

    This is the shipped code with ONE line changed, from the commit that
    fixed it. It exists so the "before" column can be regenerated by a
    reader; it is not used anywhere else and is never imported by the
    package.
    """
    from scipy import stats as sp_stats
    from itertools import combinations

    m = np.asarray(matrix, dtype=float)
    n_obs, n_cfg = m.shape
    n_splits = int(min(n_splits, (n_obs // 2) * 2))
    if n_splits % 2 == 1:
        n_splits -= 1
    block = n_obs // n_splits
    blocks = np.array_split(m[: block * n_splits], n_splits, axis=0)
    combos = list(combinations(range(n_splits), n_splits // 2))

    logits = []
    for train_idx in combos:
        test_idx = [i for i in range(n_splits) if i not in train_idx]
        train = np.concatenate([blocks[i] for i in train_idx], axis=0)
        test = np.concatenate([blocks[i] for i in test_idx], axis=0)
        best_in_sample = int(np.argmax(train.mean(axis=0)))
        rank_of_best = float(sp_stats.rankdata(test.mean(axis=0))[best_in_sample])
        n_cfg_f = float(n_cfg)
        # THE LINE THAT WAS WRONG. Zero-based rank over N.
        theta = (rank_of_best - 1.0) / n_cfg_f - 0.5
        p = float(np.clip(0.5 - theta, 1e-6, 1 - 1e-6))
        logits.append(np.log(p / (1 - p)))

    return float(np.mean([1.0 if lg < 0 else 0.0 for lg in logits]))


def _ml4t_pbo(ml4t_stats, n_cfg: int, rng: np.random.Generator) -> float:
    is_m = rng.normal(0, 1, (ML4T_COMBINATIONS, n_cfg))
    oos_m = rng.normal(0, 1, (ML4T_COMBINATIONS, n_cfg))
    res = ml4t_stats.compute_pbo(is_m, oos_m)
    return float(getattr(res, "pbo", res))


def measure(ml4t_stats=None) -> dict[str, dict[str, float]]:
    """Run the protocol and return the table, keyed by N."""
    rng = np.random.default_rng(SEED)
    rng_ml4t = np.random.default_rng(SEED)
    rows: dict[str, dict[str, float]] = {}
    for n_cfg in N_CONFIGS:
        before, after, theirs = [], [], []
        for _ in range(N_DRAWS):
            matrix = rng.normal(0.0, 0.01, (N_OBS, n_cfg))
            before.append(pbo_pre_fix(matrix))
            after.append(ha.pbo_cscv(matrix, n_splits=N_SPLITS)["pbo"])
            if ml4t_stats is not None:
                theirs.append(_ml4t_pbo(ml4t_stats, n_cfg, rng_ml4t))
        row = {
            "before": round(float(np.mean(before)), 4),
            "after": round(float(np.mean(after)), 4),
        }
        if theirs:
            row["ml4t"] = round(float(np.mean(theirs)), 4)
        row["truth"] = TRUTH
        rows[str(n_cfg)] = row
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--json", action="store_true", help="emit JSON")
    args = parser.parse_args(argv)

    ml4t_stats = None
    try:
        from ml4t.diagnostic.evaluation import stats as ml4t_stats  # noqa: PLC0415
    except ImportError:
        pass

    rows = measure(ml4t_stats)
    if args.json:
        print(json.dumps({"protocol": {
            "seed": SEED, "n_draws": N_DRAWS, "n_obs": N_OBS,
            "n_splits": N_SPLITS, "ml4t_combinations": ML4T_COMBINATIONS,
        }, "rows": rows}, indent=2))
        return 0

    head = "| N configs | before | after | ml4t | truth |"
    print(head)
    print("|---|---|---|---|---|")
    for n_cfg, row in rows.items():
        theirs = _half_up(row["ml4t"], 3) if "ml4t" in row else "n/a"
        print(f"| {n_cfg} | {_half_up(row['before'], 3)} | "
              f"{_half_up(row['after'], 3)} | {theirs} | {row['truth']} |")
    if "ml4t" not in next(iter(rows.values())):
        print("\nml4t is not installed, so that column is empty. It needs "
              "Python 3.12+.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
